function sendTokenRequest() {
    const apiUrl = "https://backendlive.nexemy.com/access/admin/login/";
    const username = "nexemyadmin@mail.com";
    const password = "nexemy@2024";

    // Prepare the payload
    const payload = {
        email: username,
        password: password
    };

    // Send the POST request
    fetch(apiUrl, {
        method: "POST",
        headers: {
            "Content-Type": "application/json", // Set the content type
        },
        body: JSON.stringify(payload) // Convert payload to JSON
    })
    .then(response => {
        if (!response.ok) {
            throw new Error(`HTTP error! Status: ${response.status}`);
        }
        return response.json(); // Parse the JSON response
    })
    .then(data => {
        if (data.status === "success" && data.data.token) {
            const token = data.data.token;
            console.log("Token:", token);

            // Redirect to the new page with the token in the URL
             // Redirect to the new page with the token in a new tab
            const newPageUrl = `https://admin.nexemy.com/dashboard/${token}`;
            window.open(newPageUrl, '_blank');  // Open the link in a new tab
        } else {
            console.error("Token not found or status is not success");
        }
    })
    .catch(error => {
        console.error("Error sending request:", error.message);
    });
}

